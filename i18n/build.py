#!/usr/bin/env python3
"""Regenerates web/i18n.js and i18n_gen.go from i18n/langs.json and
i18n/<code>.json. Each <code>.json holds every key of en.json:
"panel.*" for the admin panel, "sub.*" for the subscription page and
"act.*" for the unblocker activation page. Run after editing any of them:
    python3 i18n/build.py
"""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
langs = json.load(open(os.path.join(here, "langs.json"), encoding="utf-8"))
en = json.load(open(os.path.join(here, "en.json"), encoding="utf-8"))
data, bad = {}, False
for code, *_ in langs:
    d = json.load(open(os.path.join(here, code + ".json"), encoding="utf-8"))
    miss = [k for k in en if k not in d]
    if miss:
        print(code, "missing", miss[:10]); bad = True
    for k, v in en.items():
        if k in d and sorted(re.findall(r"\{\w+\}", v)) != sorted(re.findall(r"\{\w+\}", d[k])):
            print(code, "placeholder mismatch", k); bad = True
    data[code] = d
if bad:
    sys.exit(1)

def part(prefix):
    return {c: {k[len(prefix):]: v for k, v in d.items() if k.startswith(prefix) and k in en} for c, d in data.items()}

js = ("// Generated by i18n/build.py from i18n/*.json. Do not edit by hand.\n"
      "const XO_LANGS = " + json.dumps(langs, ensure_ascii=False) + ";\n"
      "const T = " + json.dumps(part("panel."), ensure_ascii=False, indent=0, sort_keys=True) + ";\n")
open(os.path.join(root, "web", "i18n.js"), "w", encoding="utf-8").write(js)

def gostr(o):
    return json.dumps(json.dumps(o, ensure_ascii=False, sort_keys=True), ensure_ascii=False)

go = ("// Code generated by i18n/build.py from i18n/*.json. DO NOT EDIT.\n\npackage main\n\n"
      "const i18nLangs = " + gostr(langs) + "\n\n"
      "const i18nSub = " + gostr(part("sub.")) + "\n\n"
      "const i18nAct = " + gostr(part("act.")) + "\n")
open(os.path.join(root, "i18n_gen.go"), "w", encoding="utf-8").write(go)
print("ok:", len(langs), "languages,", len(en), "keys")
